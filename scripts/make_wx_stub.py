"""Create a headless stub of wxPython inside a venv so Ink/Stitch's non-GUI extensions import.

Usage: python scripts/make_wx_stub.py <site-packages dir> <inkstitch source dir>
"""
import pathlib
import re
import sys

sp = pathlib.Path(sys.argv[1])
root = pathlib.Path(sys.argv[2])
mods = {"wx"}
pat = re.compile(r"^\s*(?:import|from)\s+(wx(?:\.[A-Za-z0-9_]+)*)", re.M)
pat2 = re.compile(r"^\s*from\s+(wx(?:\.[A-Za-z0-9_]+)*)\s+import\s+([A-Za-z0-9_, ]+)", re.M)
for p in root.rglob("*.py"):
    try:
        txt = p.read_text(errors="ignore")
    except OSError:
        continue
    for m in pat.findall(txt):
        parts = m.split(".")
        for i in range(1, len(parts) + 1):
            mods.add(".".join(parts[:i]))
    for base, names in pat2.findall(txt):
        for n in names.split(","):
            n = n.strip().split(" ")[0]
            if n and n[0].islower():
                mods.add(base + "." + n)
STUB = '''"""Headless stub of wxPython (generated by scripts/make_wx_stub.py).

Ink/Stitch imports wx at module level in its GUI extensions. Only the headless
output extension is used here, so every attribute resolves to a harmless dummy.
"""
class _Stub:
    def __init__(self, *a, **k): pass
    def __getattr__(self, name): return _Stub()
    def __call__(self, *a, **k): return _Stub()
    def __or__(self, o): return 0
    def __ror__(self, o): return 0
    def __int__(self): return 0
    def __iter__(self): return iter(())
def __getattr__(name):
    if name.startswith('__'): raise AttributeError(name)
    return _Stub
'''
for m in sorted(mods):
    d = sp.joinpath(*m.split("."))
    d.mkdir(parents=True, exist_ok=True)
    (d / "__init__.py").write_text(STUB)
print("stubbed:", ", ".join(sorted(mods)))
